    }

    /// Returns `true` when `word` is an attested or phonotactically valid onset-less Vietnamese rhyme (`vần`)
    /// containing Vietnamese diacritics (e.g. `uối`, `uồi`, `uổi`, `uỗi`, `uội`, `ọn`, `iếng`, `iết`, `uăng`, `uốc`, `uyết`).
    internal func isValidVietnameseRhyme(_ word: String) -> Bool {
        let lower = word.lowercased()
        guard lower.count >= 2,
              !lower.unicodeScalars.allSatisfy(\.isASCII),
              let first = lower.first,
              Self.allVietnameseVowels.contains(first),
              !Self.hasBreveFollowedByVowel(lower) else {
            return false
        }
        if validRhymes.contains(lower) {
            return true
        }
        let untoned = Self.stripToneMarks(lower)
        guard !untoned.unicodeScalars.allSatisfy(\.isASCII),
              untonedRhymes.contains(untoned) else {
            return false
        }
        if VietnameseEngine.endsWithStopCodaAfterVowel(Array(untoned)) {
            return Self.hasAcuteOrDotTone(lower)
        }
        return true
    }

    /// Returns `true` when `word` is a plausible in-progress or completed onset-less Vietnamese rhyme (`vần`)
    /// (e.g. `uô` -> `uôi` -> `uối`, `iê` -> `iên` -> `iêng` -> `iếng`, `ọ` -> `ọn`, `uyê` -> `uyêt` -> `uyết`).
    internal func isPlausibleInProgressVietnameseRhyme(_ word: String) -> Bool {
        let lower = word.lowercased()
        guard lower.count >= 2,
              let first = lower.first,
              Self.allVietnameseVowels.contains(first),
              !Self.hasBreveFollowedByVowel(lower),
              !Self.hasIllegalStopCodaTone(lower) else {
            return false
        }
        if validRhymes.contains(lower) || untonedRhymes.contains(lower) {
            return true
        }
        if Self.hasToneMark(lower) {
            if strictRhymePrefixes.contains(lower) ||
               unmodifiedRhymePrefixes.contains(Self.stripVowelShapeModifiers(lower)) {
                return true
            }
            let untoned = Self.stripToneMarks(lower)
            if untoned == "uo" || untoned == "ie" || untoned == "ye" {
                return true
            }
            let isShortPlainASCII = untoned.count <= 2 && untoned.unicodeScalars.allSatisfy(\.isASCII)
            if !isShortPlainASCII &&
               (untonedRhymePrefixes.contains(untoned) ||
                untonedUnmodifiedRhymePrefixes.contains(Self.stripVowelShapeModifiers(untoned))) {
                return true
            }
            return false
        } else {
            return untonedRhymePrefixes.contains(lower) ||
                untonedUnmodifiedRhymePrefixes.contains(Self.stripVowelShapeModifiers(lower))
        }
    }

    internal func isValidUntonedSyllable(_ word: String, genZMode: Bool = false) -> Bool {
        let lower = word.lowercased()
        if untonedSyllables.contains(lower) {
            return true
        }
        guard genZMode, let first = lower.first else { return false }
        let isDz = lower.hasPrefix("dz")
        let rem = isDz ? String(lower.dropFirst(2)) : String(lower.dropFirst())
        guard !rem.isEmpty else { return false }
        let prefixes: [String]
        if isDz {
            prefixes = ["d", "v", "gi"]
        } else {
            switch first {
            case "f": prefixes = ["ph"]
            case "z": prefixes = ["d", "v", "gi", "tr", "r"]
            case "j": prefixes = ["d", "gi", "v", "tr", "r"]
            case "w": prefixes = ["qu"]
            default: return false
            }
        }
        for p in prefixes {
            if untonedSyllables.contains(p + rem) {
                return true
            }
        }
        return false
    }

    /// Returns `true` when `word` is a phonotactically valid open circumflex prefix (e.g. `mâ`, `câ`, `tâ`, `bâ`)
    /// formed by a valid Vietnamese onset + `â` that is a prefix of closed syllables (`mân`, `mât`, `mâm`, `mâu`, `mây`)
    /// and whose unmodified base (`ma`, `ca`, `ta`, `ba`) is a valid open syllable.
    internal func isValidOpenCircumflexPrefix(_ word: String, genZMode: Bool = false) -> Bool {
        let lower = Self.stripToneMarks(word.lowercased())
        guard lower.last == "â" else { return false }
        if untonedPrefixes.contains(lower) &&
           untonedUnmodifiedSyllables.contains(Self.stripVowelShapeModifiers(lower)) {
            return true
        }
        guard genZMode, let first = lower.first else { return false }
        let rem = String(lower.dropFirst())
        let prefixes: [String]
        switch first {
        case "f": prefixes = ["ph"]
        case "z": prefixes = ["d", "v", "gi", "tr", "r"]
        case "j": prefixes = ["d", "gi", "v", "tr", "r"]
        case "w": prefixes = ["qu"]
        default: return false
        }
        for p in prefixes {
            let candidate = p + rem
            if untonedPrefixes.contains(candidate) &&
               untonedUnmodifiedSyllables.contains(Self.stripVowelShapeModifiers(candidate)) {
                return true
            }
        }
        return false
    }

    /// Returns `true` when `word` (with its exact current vowel shape and tone) is a prefix of an attested Vietnamese syllable.
    internal func hasStrictSyllablePrefix(_ word: String) -> Bool {
        let lower = word.lowercased()
        return strictPrefixes.contains(lower) || syllables.contains(lower)
    }

    /// Returns `true` when `word` is a phonotactically valid open breve prefix (e.g. `că`, `mă`, `tă`, `bă`)
    /// formed by a valid Vietnamese onset + `ă` that is a prefix of closed syllables (`căn`, `căt`, `căm`, `căng`, `căp`)
    /// and whose unmodified base (`ca`, `ma`, `ta`, `ba`) is a valid open syllable.
    internal func isValidOpenBrevePrefix(_ word: String, genZMode: Bool = false) -> Bool {
        let lower = Self.stripToneMarks(word.lowercased())
        guard lower.last == "ă" else { return false }
        if untonedPrefixes.contains(lower) &&
           untonedUnmodifiedSyllables.contains(Self.stripVowelShapeModifiers(lower)) {
            return true
        }
        guard genZMode, let first = lower.first else { return false }
        let rem = String(lower.dropFirst())
        let prefixes: [String]
        switch first {
        case "f": prefixes = ["ph"]
        case "z": prefixes = ["d", "v", "gi", "tr", "r"]
        case "j": prefixes = ["d", "gi", "v", "tr", "r"]
        case "w": prefixes = ["qu"]
        default: return false
        }
        for p in prefixes {
            let candidate = p + rem
            if untonedPrefixes.contains(candidate) &&
               untonedUnmodifiedSyllables.contains(Self.stripVowelShapeModifiers(candidate)) {
                return true
            }
        }
        return false
    }

    /// Returns `true` if `word` is either in `syllables` or is a phonotactically valid
    /// Vietnamese syllable whose untoned skeleton contains a Vietnamese modified character (`ă, â, ê, ô, ơ, ư, đ`),
    /// exists in `untonedSyllables` (or is a valid open circumflex/breve prefix like `mấ`, `mậ`, `cấ`, `cắ`),
    /// and satisfies Vietnamese stop-coda tone constraints (`-c, -ch, -p, -t` require Sắc or Nặng).
    /// Handles lexical tone gaps in `TuDien.txt` (e.g. `chuân`, `chuấn`, `chuần`, `chuẫn`, `chuận` alongside `chuẩn`).
    internal func isPhonotacticallyValidSyllable(_ word: String) -> Bool {
        let lower = word.lowercased()
        if lower.count > 8 {
            return false
        }
        if syllables.contains(lower) {
            return true
        }
        if Self.hasBreveFollowedByVowel(lower) {
            return false
        }
        let untoned = Self.stripToneMarks(lower)
        guard !untoned.unicodeScalars.allSatisfy({ $0.isASCII }),
              untonedSyllables.contains(untoned) ||
              isValidOpenCircumflexPrefix(untoned) ||
              isValidOpenBrevePrefix(untoned) else {
            return false
        }
        if VietnameseEngine.endsWithStopCodaAfterVowel(Array(untoned)) {
            return Self.hasAcuteOrDotTone(lower)
        }
        return true
    }

    /// Returns `true` if `word` is an informal/incomplete Vietnamese syllable that should not be
    /// reverted to raw ASCII by Smart Bilingual (e.g. `khôg` -> `không`, `kêh` -> `kênh`, `ưg` -> `ưng`,
    /// `khồg` -> `khồng`, `nhưg` -> `nhưng`, `cũg` -> `cũng`, `mìh` -> `mình`, `tìh` -> `tình`,
    /// `trươ`, `ngươ`, `viê`, `muô`, `chuyê`).
    internal func isValidRelaxedCodaVietnamese(_ word: String, raw: String = "", genZMode: Bool = false) -> Bool {
        let lower = word.lowercased()
        if lower.count > 8 {
            return false
        }
        let lowerRaw = raw.lowercased()
        let untoned = Self.stripToneMarks(lower)
        let hasModifiedShape = !untoned.unicodeScalars.allSatisfy({ $0.isASCII })
        let hasTone = Self.hasToneMark(lower)
        guard hasModifiedShape || hasTone else {
            return false
        }
        if genZMode && (lower == "ừk" || lower == "ờk" || lower == "àk") {
            return true
        }
        if Self.hasBreveFollowedByVowel(lower) || Self.hasIllegalStopCodaTone(lower) {
            return false
        }
        // 1. Open in-progress Vietnamese prefixes with explicit vowel shape modifier (`ă, â, ê, ô, ơ, ư`),
        // e.g. `trươ`, `ngươ`, `viê`, `muô`, `chuyê`, `hoă`, `đượ`, `việ`, `chuyể`
        let endsWithVowel = lower.last.map({ VietnameseEngine.isVietnameseVowel($0) }) ?? false
        if hasModifiedShape && endsWithVowel && untonedPrefixes.contains(untoned) {
            return true
        }
        // 2. Relaxed/abbreviated codas (`-g` -> `-ng`, `-h` -> `-nh`/`-ch`, `-k` -> `-c`/`-ch`)
        var expandedCandidates: [String] = []
        if lower.hasSuffix("g") && !lower.hasSuffix("ng") {
            expandedCandidates.append(String(lower.dropLast()) + "ng")
        }
        if lower.hasSuffix("h") && !lower.hasSuffix("nh") && !lower.hasSuffix("ch") && lower.count >= 2 && !lowerRaw.hasSuffix("sh") {
            expandedCandidates.append(String(lower.dropLast()) + "nh")
            expandedCandidates.append(String(lower.dropLast()) + "ch")
        }
        if lower.hasSuffix("k") && !lowerRaw.hasSuffix("sk") {
            expandedCandidates.append(String(lower.dropLast()) + "c")
            expandedCandidates.append(String(lower.dropLast()) + "ch")
        }
        for candidate in expandedCandidates {
            if hasModifiedShape {
                if isPhonotacticallyValidSyllable(candidate) {
                    return true
                }
                let candUntoned = Self.stripToneMarks(candidate)
                if !hasTone &&
                   (isValidUntonedSyllable(candUntoned, genZMode: genZMode) || untonedPrefixes.contains(candUntoned)) {
                    return true
                }
            } else if hasTone && syllables.contains(candidate) {
                return true
            }
        }
        return false
    }

    /// Returns the expanded full Vietnamese syllables for a relaxed-coda word (e.g. `khôg` -> `["không"]`,
    /// `kêh` -> `["kênh", "kêch"]`, `ưg` -> `["ưng"]`, `mìh` -> `["mình"]`, `đượk` -> `["được"]`).
    internal func expandedRelaxedCodaSyllables(_ word: String) -> [String] {
        let lower = word.lowercased()
        guard !syllables.contains(lower) else { return [] }
        var candidates: [String] = []
        if lower.hasSuffix("g") && !lower.hasSuffix("ng") {
            candidates.append(String(lower.dropLast()) + "ng")
        } else if lower.hasSuffix("h") && !lower.hasSuffix("nh") && !lower.hasSuffix("ch") && lower.count >= 2 {
            candidates.append(String(lower.dropLast()) + "nh")
            candidates.append(String(lower.dropLast()) + "ch")
        } else if lower.hasSuffix("k") {
            candidates.append(String(lower.dropLast()) + "c")
            candidates.append(String(lower.dropLast()) + "ch")
        }
        return candidates.filter { syllables.contains($0) || isValidUntonedSyllable($0) }
    }

    /// Returns `true` if `word` matches a valid Vietnamese syllable when vowel shape modifiers
    /// (`^`, `ă`, `ơ/ư`) are ignored, while still enforcing tone marks and `đ` (including stop-coda tone rules).
    internal func isValidSyllableIgnoringVowelShape(_ word: String) -> Bool {
        let lower = word.lowercased()
        if lower.count > 8 {
            return false
        }
        if syllables.contains(lower) {
            return true
        }
        if Self.hasBreveFollowedByVowel(lower) {
            return false
        }
        if unmodifiedVowelSyllables.contains(Self.stripVowelShapeModifiers(lower)) {
            return true
        }
        let untoned = Self.stripToneMarks(lower)
        let untonedUnmod = Self.stripVowelShapeModifiers(untoned)
        guard untonedUnmodifiedSyllables.contains(untonedUnmod) else {
            return false
        }
        guard !untoned.unicodeScalars.allSatisfy({ $0.isASCII }) || untonedUnmod.count >= 3 else {
            return false
        }
        if VietnameseEngine.endsWithStopCodaAfterVowel(Array(untonedUnmod)) {
            return Self.hasAcuteOrDotTone(lower)
        }
        return true
    }

    /// Returns `true` if `word` matches a valid untoned Vietnamese syllable when both tone marks
    /// and vowel shape modifiers (`^`, `ă`, `ơ/ư`) are ignored.
    internal func isValidUntonedSyllableIgnoringVowelShape(_ word: String) -> Bool {
        let lower = word.lowercased()
        if lower.count > 8 {
            return false
        }
        if untonedSyllables.contains(lower) {
            return true
        }
        if Self.hasBreveFollowedByVowel(lower) {
            return false
        }
        return untonedUnmodifiedSyllables.contains(Self.stripVowelShapeModifiers(Self.stripToneMarks(lower)))
    }

    /// Returns `true` if `word` is a valid Vietnamese syllable or a phonotactically plausible
    /// in-progress prefix of a Vietnamese syllable (including pre-horn/pre-circumflex states like
    /// `nuóng` -> `nướng`, `tuyẻn` -> `tuyển`, or pre-tone stop-coda states like `viêt` -> `việt`, `đăc` -> `đặc`).
    /// Rejects mangled mid-word English states like `rẻt`, `rẻti`, `rẻtic` (`restrict`), `sẻv`, `sẻvi` (`service`),
    /// `vạya` (`vayaj`), `gĩ` (`gix`), `ăay` (`away`), `pót` (`post`).
    /// Returns `true` if `word` is a vowel-less Vietnamese consonant abbreviation containing `đ`/`Đ`
    /// (e.g. `ĐH`, `ĐT`, `ĐW`, `ĐQ`, `ĐC`, `ĐB`, `ĐK`, `ĐN`, `ĐS`, `ĐV`, `SĐT`, `BĐS`, `HĐND`, `ĐHQG`),
    /// excluding lowercase `"đr"` (`"ddr"` tech acronym in regression corpus).
    public static func isVietnameseStrokeDConsonantAbbreviation(_ word: String) -> Bool {
        let lower = word.lowercased()
        guard lower.count >= 2, lower.contains("đ") else { return false }
        if word == "đr" { return false }
        for ch in lower {
            if ch == "đ" { continue }
            guard ch.isASCII && ch.isLetter else { return false }
            if allVietnameseVowels.contains(ch) { return false }
        }
        return true
    }

    internal func isPlausibleInProgressVietnamese(
        _ word: String,
        relaxedCoda: Bool = false,
        genZMode: Bool = false
    ) -> Bool {
        let lower = word.lowercased()
        if lower.count <= 1 || syllables.contains(lower) || untonedSyllables.contains(lower) {
            return true
        }
        if lower == "đc" || lower == "sđt" || lower == "iê" || Self.isVietnameseStrokeDConsonantAbbreviation(word) {
            return true
        }
        if lower.count > 8 || Self.hasBreveFollowedByVowel(lower) {
            return false
        }

        let toned = Self.hasToneMark(lower)
        var baseCandidates: [String] = [lower]
        if relaxedCoda || genZMode {
            if lower.hasSuffix("g") && !lower.hasSuffix("ng") {
                baseCandidates.append(String(lower.dropLast()) + "ng")
            }
            if lower.hasSuffix("k") {
                baseCandidates.append(String(lower.dropLast()) + "c")
            }
            if lower.hasSuffix("h") && !lower.hasSuffix("nh") && !lower.hasSuffix("ch") && lower.count >= 2 {
                baseCandidates.append(String(lower.dropLast()) + "nh")
            }
        }

        var candidates = baseCandidates
        if genZMode {
            for c in baseCandidates {
                if c.hasPrefix("dz") {
                    let rem = c.dropFirst(2)
                    candidates.append("d" + rem)
                    candidates.append("v" + rem)
                    candidates.append("gi" + rem)
                } else if c.hasPrefix("f") {
                    candidates.append("ph" + c.dropFirst())
                } else if c.hasPrefix("z") {
                    let rem = c.dropFirst()
                    candidates.append("d" + rem)
                    candidates.append("v" + rem)
                    candidates.append("gi" + rem)
                    candidates.append("tr" + rem)
                    candidates.append("r" + rem)
                    candidates.append("qu" + rem)
                } else if c.hasPrefix("j") {
                    let rem = c.dropFirst()
                    candidates.append("d" + rem)
                    candidates.append("gi" + rem)
                    candidates.append("v" + rem)
                    candidates.append("tr" + rem)
                    candidates.append("r" + rem)
                } else if c.hasPrefix("w") {
                    candidates.append("qu" + c.dropFirst())
                }
            }
        }

        for candidate in candidates {
            if toned {
                if strictPrefixes.contains(candidate) ||
                   unmodifiedVowelPrefixes.contains(Self.stripVowelShapeModifiers(candidate)) {
                    return true
                }
                let untoned = Self.stripToneMarks(candidate)
                let isShortPlainASCII = untoned.count <= 2 && untoned.unicodeScalars.allSatisfy({ $0.isASCII })
                if !isShortPlainASCII && !Self.hasIllegalStopCodaTone(candidate) {
                    if untonedPrefixes.contains(untoned) ||
                       untonedUnmodifiedPrefixes.contains(Self.stripVowelShapeModifiers(untoned)) {
                        return true
                    }
                }
            } else {
                if untonedPrefixes.contains(candidate) ||
                   untonedUnmodifiedPrefixes.contains(Self.stripVowelShapeModifiers(candidate)) {
                    return true
                }
            }
        }
        return false
    }

    internal func hasUntonedPrefix(
        _ word: String,
        preserveVowelShape: Bool,
        relaxedCoda: Bool = true,
        genZMode: Bool = true
    ) -> Bool {
        let lower = word.lowercased()
        if lower.count > 8 {
            return false
        }
        let stripped = Self.stripToneMarks(lower)
        let harmonized = stripped.contains("ưo") ? stripped.replacingOccurrences(of: "ưo", with: "ươ") : stripped
        if Self.hasBreveFollowedByVowel(harmonized) {
            return false
        }
        var baseCandidates: [String] = [harmonized]
        if relaxedCoda || genZMode {
            if harmonized.hasSuffix("g") && !harmonized.hasSuffix("ng") {
                baseCandidates.append(String(harmonized.dropLast()) + "ng")
            }
            if harmonized.hasSuffix("k") {
                baseCandidates.append(String(harmonized.dropLast()) + "c")
            }
            if harmonized.hasSuffix("h") && !harmonized.hasSuffix("nh") && !harmonized.hasSuffix("ch") && harmonized.count >= 2 {
                baseCandidates.append(String(harmonized.dropLast()) + "nh")
            }
        }
        var candidates = baseCandidates
        if genZMode {
            for c in baseCandidates {
                if c.hasPrefix("dz") {
                    let rem = c.dropFirst(2)
                    candidates.append("d" + rem)
                    candidates.append("v" + rem)
                    candidates.append("gi" + rem)
                } else if c.hasPrefix("f") {
                    candidates.append("ph" + c.dropFirst())
                } else if c.hasPrefix("z") {
                    let rem = c.dropFirst()
                    candidates.append("d" + rem)
                    candidates.append("v" + rem)
                    candidates.append("gi" + rem)
                    candidates.append("tr" + rem)
                    candidates.append("r" + rem)
                    candidates.append("qu" + rem)
                } else if c.hasPrefix("j") {
                    let rem = c.dropFirst()
                    candidates.append("d" + rem)
                    candidates.append("gi" + rem)
                    candidates.append("v" + rem)
                    candidates.append("tr" + rem)
                    candidates.append("r" + rem)
                } else if c.hasPrefix("w") {
                    candidates.append("qu" + c.dropFirst())
                }
            }
        }
        for candidate in candidates {
            if untonedPrefixes.contains(candidate) {
                return true
            }
            if !preserveVowelShape && untonedUnmodifiedPrefixes.contains(Self.stripVowelShapeModifiers(candidate)) {
                return true
            }
        }
        return false
    }

    private static let breveVowels: Set<Character> = ["ă", "ắ", "ằ", "ẳ", "ẵ", "ặ"]
    private static let allVietnameseVowels: Set<Character> = [
        "a", "e", "i", "o", "u", "y", "ă", "â", "ê", "ô", "ơ", "ư",
        "á", "à", "ả", "ã", "ạ", "ắ", "ằ", "ẳ", "ẵ", "ặ",
        "ấ", "ầ", "ẩ", "ẫ", "ậ", "é", "è", "ẻ", "ẽ", "ẹ",
        "ế", "ề", "ể", "ễ", "ệ", "í", "ì", "ỉ", "ĩ", "ị",
        "ó", "ò", "ỏ", "õ", "ọ", "ố", "ồ", "ổ", "ỗ", "ộ",
        "ớ", "ờ", "ở", "ỡ", "ợ", "ú", "ù", "ủ", "ũ", "ụ",
        "ứ", "ừ", "ử", "ữ", "ự", "ý", "ỳ", "ỷ", "ỹ", "ỵ"
    ]

    private static func hasBreveFollowedByVowel(_ lower: String) -> Bool {
        if lower.unicodeScalars.allSatisfy(\.isASCII) { return false }
        let chars = Array(lower)
        guard chars.count >= 2 else { return false }
        for i in 0..<(chars.count - 1) {
            if breveVowels.contains(chars[i]) && allVietnameseVowels.contains(chars[i + 1]) {
                return true
            }
        }
        return false
    }

