    internal static func hasToneMark(_ str: String) -> Bool {
        for scalar in str.unicodeScalars {
            if scalar.value >= 0x80 && toneKindOfScalar(scalar.value) != 0 {
                return true
            }
        }
        return false
    }

    internal static func hasAcuteOrDotTone(_ str: String) -> Bool {
        for scalar in str.unicodeScalars {
            if scalar.value >= 0x80 && toneKindOfScalar(scalar.value) == 1 {
                return true
            }
        }
        return false
    }

    internal static func hasNonStopTone(_ str: String) -> Bool {
        for scalar in str.unicodeScalars {
            if scalar.value >= 0x80 && toneKindOfScalar(scalar.value) == 2 {
                return true
            }
        }
        return false
    }

    private static func hasIllegalStopCodaTone(_ lower: String) -> Bool {
        let untoned = stripToneMarks(lower)
        if VietnameseEngine.endsWithStopCodaAfterVowel(Array(untoned)) {
            return hasNonStopTone(lower)
        }
        return false
    }

    private static func stripVowelShapeModifiers(_ str: String) -> String {
        var needsChange = false
        var hasCombining = false
        for s in str.unicodeScalars {
            if s.value >= 0x80 {
                if s.value >= 0x0300 && s.value <= 0x036F {
                    hasCombining = true
                    needsChange = true
                    break
                }
                if unshapedScalar(s) != s {
                    needsChange = true
                }
            }
        }
        if !needsChange { return str }
        if hasCombining {
            var scalars = String.UnicodeScalarView()
            for scalar in str.decomposedStringWithCanonicalMapping.unicodeScalars {
                switch scalar.value {
                case 0x0302, 0x0306, 0x031B:
                    continue
                default:
                    scalars.append(scalar)
                }
            }
            return String(scalars).precomposedStringWithCanonicalMapping
        }
        var out = String.UnicodeScalarView()
        out.reserveCapacity(str.unicodeScalars.count)
        for s in str.unicodeScalars {
            out.append(s.value >= 0x80 ? unshapedScalar(s) : s)
        }
        return String(out)
    }

    internal static func stripToneMarks(_ str: String) -> String {
        var needsChange = false
        var hasCombining = false
        for s in str.unicodeScalars {
            if s.value >= 0x80 {
                if s.value >= 0x0300 && s.value <= 0x036F {
                    hasCombining = true
                    needsChange = true
                    break
                }
                if toneKindOfScalar(s.value) != 0 {
                    needsChange = true
                }
            }
        }
        if !needsChange { return str }
        if hasCombining {
            var scalars = String.UnicodeScalarView()
            for scalar in str.decomposedStringWithCanonicalMapping.unicodeScalars {
                switch scalar.value {
                case 0x0300, 0x0301, 0x0303, 0x0309, 0x0323:
                    continue
                default:
                    scalars.append(scalar)
                }
            }
            return String(scalars).precomposedStringWithCanonicalMapping
        }
        var out = String.UnicodeScalarView()
        out.reserveCapacity(str.unicodeScalars.count)
        for s in str.unicodeScalars {
            out.append(s.value >= 0x80 ? untonedScalar(s) : s)
        }
        return String(out)
    }
