    private static func decodeSyllableString() -> String {
        var bytes = [UInt8]()
        bytes.reserveCapacity(encodedSyllableWords.count * 8)
        for (idx, word) in encodedSyllableWords.enumerated() {
            let key = UInt64(truncatingIfNeeded: idx) &* 0x9E3779B97F4A7C15 &+ 0xBF58476D1CE4E5B9
            var plain = (word ^ key).littleEndian
            withUnsafeBytes(of: &plain) { buf in
                bytes.append(contentsOf: buf)
            }
        }
        return String(decoding: bytes.prefix(encodedSyllableByteCount), as: UTF8.self)
    }

